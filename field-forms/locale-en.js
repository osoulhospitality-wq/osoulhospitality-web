  function localizeTemplates(definitions) {
    for (const definition of definitions) {
      const labels = templates[definition.code];
      if (!labels) continue;
      definition.name = labels.name;
      definition.owner = labels.owner;
      definition.frequency = labels.frequency;
      for (const field of definition.fields) {
        field.label = labels.fields[field.key] ?? field.label;
        if (field.hint) field.hint = labels.hints[field.key] ?? field.hint;
      }
    }
  }
  function booleanControl(code, key, editable, current) {
    if (!((code === "F04" && key === "C12") || (code === "F17" && key === "C15"))) return null;
    const select = document.createElement("select");
    select.disabled = !editable;
    select.append(new Option("Select an answer", ""), new Option("Yes", "نعم"), new Option("No", "لا"));
    if (current && !Array.from(select.options).some(option => option.value === current)) {
      select.add(new Option(current, current));
    }
    return select;
  }
