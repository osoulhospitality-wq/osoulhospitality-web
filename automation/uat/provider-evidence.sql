-- roll back. This exercises database RLS/receipts; it does not transfer file bytes.
begin;
do $test$
declare
 principals uuid[]; manager uuid; author uuid; org uuid:=gen_random_uuid(); vendor uuid:=gen_random_uuid(); other uuid:=gen_random_uuid();
 contract uuid:=gen_random_uuid(); sub uuid; path text; abandoned text; late text; ok integer; receipt jsonb;
begin
 select array(select id from auth.users where email like '%.invalid' order by id limit 2) into principals;
 assert cardinality(principals)=2;
 manager:=principals[1];author:=principals[2];
 perform set_config('request.jwt.claims',jsonb_build_object('sub',manager,'aal','aal2')::text,true);
 insert into public.organizations(id,name,created_by) values(org,'QA Provider Evidence',manager);
 insert into public.suppliers(id,name,organization_id,created_by) values(vendor,'QA provider files',org,manager),(other,'QA unrelated supplier',org,manager);
 insert into public.contracts(id,name,organization_id,supplier_id,created_by) values(contract,'QA evidence scope',org,vendor,manager);
 insert into private.fm_provider_accounts(supplier_id,user_id) values(vendor,author);
 assert exists(select 1 from storage.buckets where id='provider-evidence' and not public and file_size_limit=6291456 and cardinality(allowed_mime_types)=3);
 execute 'set local role authenticated';
 perform set_config('request.jwt.claims',jsonb_build_object('sub',author,'aal','aal2')::text,true);
 sub:=public.fm_provider_submit(contract,gen_random_uuid(),'visit_report','QA metadata','Synthetic evidence exercise');
 path:=public.fm_provider_prepare_file(sub,'image/png',8);
 begin perform public.fm_provider_prepare_file(sub,'text/html',8); raise exception 'Invalid type allowed'; exception when check_violation then null; end;
 begin perform public.fm_provider_prepare_file(sub,'image/png',6291457); raise exception 'Invalid size allowed'; exception when check_violation then null; end;
 begin perform public.fm_provider_confirm_file(sub,path);raise exception 'Confirmed without upload';exception when others then if sqlerrm<>'Uploaded content does not match receipt' then raise; end if;end;
 perform set_config('storage.operation','storage.object.upload',true);
 insert into storage.objects(bucket_id,name,owner_id,metadata) values('provider-evidence',path,author::text,jsonb_build_object('mimetype','image/png','size',8));
 assert jsonb_array_length(public.fm_provider_file_list(sub)->'files')=0;
 assert public.fm_provider_confirm_file(sub,path);
 assert public.fm_provider_confirm_file(sub,path);
 perform set_config('storage.operation','storage.object.get_authenticated',true);
 select count(*) into ok from storage.objects where bucket_id='provider-evidence' and name=path;
 assert ok=1;
 perform set_config('storage.operation','storage.object.sign',true);
 select count(*) into ok from storage.objects where bucket_id='provider-evidence' and name=path;
 assert ok=0;
 perform set_config('storage.operation','storage.object.delete_many',true);
 select count(*) into ok from storage.objects where bucket_id='provider-evidence' and name=path; assert ok=0;
 assert not public.fm_provider_abandon_file(sub,path);
 begin perform public.fm_review_submission_with_evidence(sub,'accepted','QA',1);raise exception 'Author reviewed own evidence'; exception when insufficient_privilege then null;end;
 abandoned:=public.fm_provider_prepare_file(sub,'image/jpeg',3);
 perform set_config('storage.operation','storage.object.upload',true);
 insert into storage.objects(bucket_id,name,owner_id,metadata) values('provider-evidence',abandoned,author::text,'{"mimetype":"image/jpeg","size":3}');
 assert public.fm_provider_abandon_file(sub,abandoned);
 perform set_config('storage.operation','storage.object.delete_many',true);
 select count(*) into ok from storage.objects where bucket_id='provider-evidence' and name=abandoned; assert ok=1;
 late:=public.fm_provider_prepare_file(sub,'application/pdf',5);
 perform set_config('storage.operation','storage.object.upload',true);
 insert into storage.objects(bucket_id,name,owner_id,metadata) values('provider-evidence',late,author::text,'{"mimetype":"application/pdf","size":5}');
 execute 'reset role';
 update private.fm_provider_accounts set active=false where supplier_id=vendor and user_id=author;
 insert into private.fm_provider_accounts(supplier_id,user_id) values(other,author);
 execute 'set local role authenticated';
 begin perform public.fm_provider_file_list(sub);raise exception 'Competing supplier read';exception when insufficient_privilege then null;end;
 perform set_config('storage.operation','storage.object.get_authenticated',true);
 select count(*) into ok from storage.objects where bucket_id='provider-evidence' and name=path;assert ok=0;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',manager,'aal','aal1')::text,true);
 begin perform public.fm_provider_file_list(sub);raise exception 'Weak session read';exception when insufficient_privilege then null;end;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',manager,'aal','aal2')::text,true);
 receipt:=public.fm_provider_file_list(sub); assert (receipt->>'can_upload')::boolean=false and jsonb_array_length(receipt->'files')=1 and jsonb_array_length(receipt->'pending')=1 and receipt->'pending'->0->>'path'=abandoned;
 select count(*) into ok from storage.objects where bucket_id='provider-evidence' and name=path;assert ok=1;
 begin perform public.fm_provider_prepare_file(sub,'image/png',8);raise exception 'Reviewer uploaded';exception when insufficient_privilege then null;end;
 begin perform public.fm_review_submission(sub,'accepted','QA');raise exception 'Old review bypass';exception when serialization_failure then null;end;
 assert (public.fm_provider_file_list(sub)->>'pending_count')::integer=1;
 begin perform public.fm_review_submission_with_evidence(sub,'accepted','QA',1);raise exception 'Review while attachment is pending'; exception when serialization_failure then null; end;
 execute 'reset role';
 update private.fm_provider_files set expires_at=clock_timestamp()-interval '1 second' where object_name=late;
 execute 'set local role authenticated';
 assert jsonb_array_length(public.fm_provider_file_list(sub)->'pending')=2;
 perform set_config('storage.operation','storage.object.delete_many',true);
 select count(*) into ok from storage.objects where bucket_id='provider-evidence' and name=late; assert ok=1;
 select count(*) into ok from storage.objects where bucket_id='provider-evidence' and name=path; assert ok=0;
 assert public.fm_review_submission_with_evidence(sub,'accepted','QA',1)=sub;
 execute 'reset role';update private.fm_provider_accounts set active=true where supplier_id=vendor and user_id=author;
 execute 'set local role authenticated';
 perform set_config('request.jwt.claims',jsonb_build_object('sub',author,'aal','aal2')::text,true);
 assert public.fm_provider_confirm_file(sub,path);
 begin perform public.fm_provider_confirm_file(sub,late);raise exception 'Late evidence accepted';exception when others then if sqlerrm<>'Attachment window closed' then raise;end if;end;
 assert jsonb_array_length(public.fm_provider_file_list(sub)->'files')=1;
 assert public.fm_provider_abandon_file(sub,late);
 execute 'reset role';
end $test$;
select 'passed' as provider_evidence_preview;
